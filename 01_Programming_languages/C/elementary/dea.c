#include<stdio.h>
int main()
{   /*************************************************************************************/
    int i, n , pos , ar[10] ;
    
    /*************************************************************************************/
    printf("ent no. of elements\n");
    scanf("%d",&n);

    /*************************************************************************************/
    printf("enter elements\n");
    for ( i = 0; i < n; i++)
    {
        scanf("%d" , &ar[i]);
    }

    /*************************************************************************************/
    printf("enter position\n");
    scanf("%d" , &pos);

    /*************************************************************************************/
    for ( i = pos ; i <= n-1; i++)
    {
        ar[i] = ar[i+1];
    }
    n--;

    /*************************************************************************************/
    printf("array after del\n");
    for ( i = 0; i < n; i++)
    {
        printf("%d\t" , ar[i]);
    }
    
    /*************************************************************************************/
    return 0;

    
}