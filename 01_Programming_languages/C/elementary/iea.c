#include<stdio.h>
int main()
{   /*************************************************************************************/
    int i, n , pos , x , ar[10] ;
    
    /*************************************************************************************/
    printf("ent no. of elements\n");
    scanf("%d",&n);

    /*************************************************************************************/
    printf("enter elements");
    for ( i = 0; i < n; i++)
    {
        scanf("%d" , &ar[i]);
    }

    /*************************************************************************************/
    printf("enter no. to be inserted\n");
    scanf("%d",&x);

    /*************************************************************************************/
    printf("enter position\n");
    scanf("%d" , &pos);

    /*************************************************************************************/
    for ( i = n-1; i >=pos; i--)
    {
        ar[i+1] = ar[i];
    }

    ar[pos] = x ;
    n++;

    /*************************************************************************************/
    printf("array after ins\n");
    for ( i = 0; i < n; i++)
    {
        printf("%d\t" , ar[i]);
    }
    
    /*************************************************************************************/
    return 0;

    
}