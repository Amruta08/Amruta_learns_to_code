#include<stdio.h>
int main()
{   /*************************************************************************************/
    int arr1[5] , arr2[5] , arr[10];
    int i  , index = 0 ;

    /*************************************************************************************/
    printf("enter elements for array 1\n");
    for ( i = 0; i < 5; i++)
    {
        scanf("%d" , &arr1[i]);
    }
    
    /*************************************************************************************/
    printf("\nenter elements for array 2");
    for ( i = 0; i < 5; i++)
    {
        scanf("%d" , &arr2[i]);
    }
    
    /*************************************************************************************/
    //merging operation

    for ( i = 0; i < 5; i++)
    {
        arr[index] = arr1[i];
        index++;
    }

    for ( i = 0; i < 5; i++)
    {
        arr[index] = arr2[i];
        index++;
    }
    
    /*************************************************************************************/
    for ( i = 0; i < 10; i++)
    {
        printf("%d\t",arr[i]);
    }
    /*************************************************************************************/
    return 0 ;
}
